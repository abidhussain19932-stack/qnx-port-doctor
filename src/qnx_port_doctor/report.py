"""Text, JSON, SARIF 2.1.0 and HTML reports."""
from __future__ import annotations

import html
import json

from . import __version__
from .rules import RULES, RULES_BY_ID
from .scanner import Finding, summarize

SARIF_LEVEL = {"error": "error", "warning": "warning", "note": "note"}


def to_text(findings: list[Finding]) -> str:
    lines = []
    for f in findings:
        lines.append(f"{f.path}:{f.line}:{f.column}: {f.severity} [{f.rule_id}] {f.title}")
        lines.append(f"    {f.snippet}")
        lines.append(f"    QNX 8.0: {f.advice}")
    s = summarize(findings)
    lines.append(f"\n{s['error']} error(s), {s['warning']} warning(s), {s['note']} note(s) "
                 f"in {s['files']} file(s). QNX portability score: {s['score']}/100")
    return "\n".join(lines)


def to_json(findings: list[Finding]) -> str:
    return json.dumps({"summary": summarize(findings),
                       "findings": [f.to_dict() for f in findings]}, indent=2)


def to_sarif(findings: list[Finding]) -> str:
    used = sorted({f.rule_id for f in findings})
    rules = [{
        "id": r.id, "name": r.title.replace(" ", ""),
        "shortDescription": {"text": r.title},
        "fullDescription": {"text": r.qnx_equivalent},
        "helpUri": r.docs,
        "defaultConfiguration": {"level": SARIF_LEVEL[r.severity]},
    } for r in (RULES_BY_ID[i] for i in used)]
    results = [{
        "ruleId": f.rule_id, "level": SARIF_LEVEL[f.severity],
        "message": {"text": f"{f.title}. QNX 8.0: {f.advice}"},
        "locations": [{"physicalLocation": {
            "artifactLocation": {"uri": f.path},
            "region": {"startLine": f.line, "startColumn": f.column}}}],
    } for f in findings]
    doc = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{"tool": {"driver": {
            "name": "qnx-port-doctor", "version": __version__,
            "informationUri": "https://github.com/abidhussain19932-stack/qnx-port-doctor",
            "rules": rules}}, "results": results}],
    }
    return json.dumps(doc, indent=2)


def to_html(findings: list[Finding], project: str = "project", runlog: str | None = None) -> str:
    s = summarize(findings)
    e = html.escape
    rows = "\n".join(
        f"<tr class='{f.severity}'><td>{e(f.severity)}</td><td>{e(f.rule_id)}</td>"
        f"<td><code>{e(f.path)}:{f.line}</code></td><td><code>{e(f.snippet)}</code></td>"
        f"<td>{e(f.advice)}</td></tr>" for f in findings)
    run = f"<h2>QNX target run</h2><pre>{e(runlog)}</pre>" if runlog else ""
    return f"""<!doctype html><html><head><meta charset="utf-8">
<title>QNX Port Doctor - {e(project)}</title>
<style>body{{font-family:system-ui,sans-serif;margin:2rem;max-width:1200px}}
table{{border-collapse:collapse;width:100%}}td,th{{border:1px solid #ddd;padding:6px;vertical-align:top;font-size:14px}}
tr.error td:first-child{{color:#b00020;font-weight:bold}}tr.warning td:first-child{{color:#b26a00}}
tr.note td:first-child{{color:#555}}.score{{font-size:2.5rem;font-weight:bold}}pre{{background:#111;color:#0f0;padding:1rem;overflow:auto}}</style>
</head><body><h1>QNX Port Doctor report: {e(project)}</h1>
<p>Target: QNX Neutrino 8.0 (SDP 8.0), toolchain qcc. Generated by qnx-port-doctor {__version__}.</p>
<p class="score">{s['score']}/100</p>
<p>{s['error']} errors, {s['warning']} warnings, {s['note']} notes in {s['files']} files.</p>
<table><tr><th>Severity</th><th>Rule</th><th>Location</th><th>Code</th><th>QNX 8.0 fix</th></tr>
{rows}</table>{run}</body></html>"""


def rules_table() -> str:
    return "\n".join(f"{r.id}  {r.severity:<7}  {r.title}" for r in RULES)
