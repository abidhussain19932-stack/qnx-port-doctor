"""Generates QNX 8.0 build files for a C/C++ project."""
from __future__ import annotations

from pathlib import Path

ARCHES = {
    "x86_64": {"variant": "gcc_ntox86_64", "processor": "x86_64", "triple": "x86_64-pc-nto-qnx8.0.0"},
    "aarch64le": {"variant": "gcc_ntoaarch64le", "processor": "aarch64", "triple": "aarch64-unknown-nto-qnx8.0.0"},
}

TOOLCHAIN = """# QNX 8.0 CMake toolchain file - generated by qnx-port-doctor
# Usage: source ~/qnx800/qnxsdp-env.sh
#        cmake -B build-qnx -DCMAKE_TOOLCHAIN_FILE=qnx/qnx800-{arch}.cmake
set(CMAKE_SYSTEM_NAME QNX)
set(CMAKE_SYSTEM_VERSION 8.0.0)
set(CMAKE_SYSTEM_PROCESSOR {processor})

if(NOT DEFINED ENV{{QNX_HOST}} OR NOT DEFINED ENV{{QNX_TARGET}})
  message(FATAL_ERROR "Source qnxsdp-env.sh from your QNX SDP 8.0 install first")
endif()
set(QNX_HOST   $ENV{{QNX_HOST}})
set(QNX_TARGET $ENV{{QNX_TARGET}})

set(CMAKE_C_COMPILER   ${{QNX_HOST}}/usr/bin/qcc)
set(CMAKE_CXX_COMPILER ${{QNX_HOST}}/usr/bin/q++)
set(CMAKE_C_COMPILER_TARGET   {variant})
set(CMAKE_CXX_COMPILER_TARGET {variant}_cxx)
set(CMAKE_C_FLAGS_INIT   "-V{variant} -D_QNX_SOURCE")
set(CMAKE_CXX_FLAGS_INIT "-V{variant}_cxx -D_QNX_SOURCE")
set(CMAKE_AR     ${{QNX_HOST}}/usr/bin/nto{processor}-ar   CACHE FILEPATH "ar")
set(CMAKE_RANLIB ${{QNX_HOST}}/usr/bin/nto{processor}-ranlib CACHE FILEPATH "ranlib")
set(CMAKE_SYSROOT ${{QNX_TARGET}})
set(CMAKE_FIND_ROOT_PATH ${{QNX_TARGET}} ${{QNX_TARGET}}/{processor})
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
"""

MAKEFILE = """# QNX 8.0 Makefile - generated by qnx-port-doctor
# Usage: source ~/qnx800/qnxsdp-env.sh && make -f Makefile.qnx ARCH={arch}
ARCH    ?= {arch}
CC      := qcc
VARIANT_x86_64    := gcc_ntox86_64
VARIANT_aarch64le := gcc_ntoaarch64le
CFLAGS  += -V$(VARIANT_$(ARCH)) -D_QNX_SOURCE -O2 -Wall -Wextra {includes}
LDLIBS  += -lsocket
SRCS    := {sources}
OUT     := build-qnx/$(ARCH)
OBJS    := $(SRCS:%.c=$(OUT)/%.o)
BIN     := $(OUT)/{name}

all: $(BIN)
$(BIN): $(OBJS)
\t$(CC) $(CFLAGS) -o $@ $^ $(LDLIBS)
$(OUT)/%.o: %.c
\t@mkdir -p $(dir $@)
\t$(CC) $(CFLAGS) -c -o $@ $<
clean:
\trm -rf build-qnx
.PHONY: all clean
"""


def generate(project: Path, arch: str = "x86_64", name: str | None = None) -> list[Path]:
    if arch not in ARCHES:
        raise ValueError(f"unknown arch {arch}; choose from {', '.join(ARCHES)}")
    project = Path(project).resolve()
    a = ARCHES[arch]
    name = name or project.name
    out_dir = project / "qnx"
    out_dir.mkdir(exist_ok=True)
    tc = out_dir / f"qnx800-{arch}.cmake"
    tc.write_text(TOOLCHAIN.format(arch=arch, **a))
    sources = sorted(p.relative_to(project).as_posix() for p in project.rglob("*.c")
                     if not any(part.startswith("build") for part in p.relative_to(project).parts))
    incs = sorted({"-I" + (p.parent.relative_to(project).as_posix() or ".") for p in project.rglob("*.h")})
    mk = project / "Makefile.qnx"
    mk.write_text(MAKEFILE.format(arch=arch, name=name, sources=" ".join(sources),
                                  includes=" ".join(incs)))
    return [tc, mk]
